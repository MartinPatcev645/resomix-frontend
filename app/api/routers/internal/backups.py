"""
Internal Backup Metrics Hook
============================

Where the backup agents on the two servers report what they did. Each script
already writes a JSON metrics file on every exit path, success or failure; this
is the endpoint that posts it somewhere an admin can read without an SSH
session.

  • ``POST /internal/backups/metrics``  — one component's result
  • ``POST /internal/backups/finish``   — the nightly wrapper has exited

Guarded by ``BACKUP_AGENT_TOKEN`` (header ``X-Internal-Key``), a token separate
from ``HETZNER_INTERNAL_API_KEY``. Separate because these calls come from a root
cron job on two boxes rather than from the media application, and one shared
secret across every internal path means rotating any of them rotates all of
them.

WHY THE STATUS IS NOT TAKEN FROM THE PAYLOAD

The run's status is derived from its components in the service layer. An agent
can crash between finishing a component and reporting the run, so a wrapper that
exits 0 must not be able to mark a night green when a component inside it failed.

Version: 1.0.0
Date: August 2026
"""

import logging
from typing import Any, Dict, Optional

from fastapi import APIRouter, Body, Depends, Header, HTTPException
from pydantic import BaseModel, Field
from sqlalchemy.ext.asyncio import AsyncSession

from app.controllers.admin_backup_controller import AdminBackupController
from app.core.config import settings
from database.connection import get_async_db

logger = logging.getLogger(__name__)

router = APIRouter(tags=["Internal Backups"])
controller = AdminBackupController()


async def verify_backup_agent_key(x_internal_key: Optional[str] = Header(default=None)) -> None:
    """Reject calls without the backup agent token.

    An unset token means the hook is closed, not open: a deployment that forgot
    the variable must fail loudly rather than accept metrics from anyone.
    """
    expected = getattr(settings, "backup_agent_token", None)
    if not expected or x_internal_key != expected:
        raise HTTPException(status_code=401, detail="Invalid or missing internal key")


class ComponentMetrics(BaseModel):
    run_uid: str = Field(..., description="Run identifier generated by the agent (UTC compact timestamp)")
    server_role: str = Field(..., description="alwyzon | media")
    component: str = Field(..., description="db | secrets | media-embeddings | media-uploads | analysis-results | verify | retention")
    status: str = Field(..., description="succeeded | failed | skipped | running | pending")

    hostname: Optional[str] = None
    trigger: Optional[str] = None
    run_started_at: Optional[str] = None
    started_at: Optional[str] = None
    finished_at: Optional[str] = None
    duration_s: Optional[int] = None

    snapshot_id: Optional[str] = None
    files_new: Optional[Any] = None
    files_changed: Optional[Any] = None
    files_processed: Optional[Any] = None
    bytes_processed: Optional[Any] = None
    # Logical, pre-compression. Kept alongside bytes_stored rather than instead
    # of it, because the two differ by the compression ratio and reporting this
    # one as storage growth overstates it several times over.
    bytes_added: Optional[Any] = None
    bytes_stored: Optional[Any] = None
    error: Optional[str] = None


class FinishRun(BaseModel):
    run_uid: str
    error: Optional[str] = Field(default=None, description="Wrapper-level failure, if any")


@router.post(
    "/internal/backups/metrics",
    summary="Record one backup component's metrics",
    dependencies=[Depends(verify_backup_agent_key)],
)
async def record_metrics(
    payload: ComponentMetrics = Body(...),
    db: AsyncSession = Depends(get_async_db),
):
    """Idempotent on ``(run_uid, component)``.

    Called over the network by a shell script, so a retry after a lost response
    is the normal case. It updates the existing row rather than adding a second,
    contradictory record of the same component.
    """
    body: Dict[str, Any] = payload.model_dump(exclude={"run_uid", "server_role", "component"})
    return await controller.ingest_component(
        db,
        run_uid=payload.run_uid,
        server_role=payload.server_role,
        component=payload.component,
        payload=body,
    )


@router.post(
    "/internal/backups/finish",
    summary="Mark a backup run finished (status is still derived from its components)",
    dependencies=[Depends(verify_backup_agent_key)],
)
async def finish_run(
    payload: FinishRun = Body(...),
    db: AsyncSession = Depends(get_async_db),
):
    return await controller.finish_run(db, run_uid=payload.run_uid, error=payload.error)
