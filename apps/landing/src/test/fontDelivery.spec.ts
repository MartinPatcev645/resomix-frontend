import { describe, it, expect } from 'vitest';
import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs';
import { resolve } from 'node:path';

/**
 * Fonts were the single biggest performance problem on the site.
 *
 * The originals shipped from `public/fonts` as `.otf`/`.ttf` — 12 MB per app, 47 files, no woff2 —
 * and each Helvetica Neue face carried ~2,200 codepoints (Latin, Greek, Cyrillic, Georgian,
 * Cherokee). The eight faces the homepage uses came to 994 KiB on the wire. Lighthouse put a font
 * at the END of the critical path on both mobile (1,766 ms) and desktop (4,403 ms), and attributed
 * 100% of the desktop CLS (0.087) to font swap.
 *
 * They are now subset woff2 with a `unicode-range` split, generated by `tooling/buildFonts.py`.
 * These assertions guard the delivery contract — the failure modes here are silent: a dangling
 * `url()` renders a fallback font nobody notices in review, and a dangling `<link rel=preload>`
 * costs a request and warns in the console.
 */

const ROOT = resolve(process.cwd(), '../..');
const APPS = ['landing', 'webapp'] as const;

const cssFor = (app: string) =>
  readFileSync(resolve(ROOT, `apps/${app}/src/styles/fonts.css`), 'utf8');
const fontsDir = (app: string) => resolve(ROOT, `apps/${app}/public/fonts`);
const urlsIn = (css: string) => [...css.matchAll(/url\('\/fonts\/([^']+)'\)/g)].map((m) => m[1]);

describe.each(APPS)('%s font delivery', (app) => {
  const css = cssFor(app);
  const dir = fontsDir(app);
  const files = readdirSync(dir);

  it('every @font-face url resolves to a real file', () => {
    const missing = urlsIn(css).filter((u) => !existsSync(resolve(dir, u)));
    expect(missing, 'dangling font references render a fallback silently').toEqual([]);
  });

  it('ships no unreferenced font files', () => {
    const referenced = new Set(urlsIn(css));
    expect(files.filter((f) => !referenced.has(f))).toEqual([]);
  });

  it('serves woff2 only', () => {
    // The originals are ~3x larger on the wire and are kept out of the deploy, in /fonts-src.
    expect(files.filter((f) => !f.endsWith('.woff2'))).toEqual([]);
  });

  it('declares a unicode-range on every face', () => {
    const faces = css.match(/@font-face\s*\{[^}]*\}/g) ?? [];
    expect(faces.length).toBeGreaterThan(0);
    expect(faces.filter((f) => !f.includes('unicode-range'))).toEqual([]);
  });

  it('splits each face into latin + ext', () => {
    // A face with only one of the two would silently lose Greek/Cyrillic, or lose everything else.
    const bases = new Set(urlsIn(css).map((u) => u.replace(/\.(latin|ext)\.woff2$/, '')));
    for (const b of bases) {
      expect(files, `${b} is missing a variant`).toContain(`${b}.latin.woff2`);
      expect(files, `${b} is missing a variant`).toContain(`${b}.ext.woff2`);
    }
  });

  it('keeps font-display: swap, so text is never invisible', () => {
    const faces = css.match(/@font-face\s*\{[^}]*\}/g) ?? [];
    expect(faces.filter((f) => !/font-display:\s*swap/.test(f))).toEqual([]);
  });

  it('has dropped Montserrat entirely', () => {
    // 18 faces, 4.6 MB, referenced by nothing outside fonts.css.
    // Comments stripped: the generated header explains the removal by name, and asserting against
    // raw text would flag that explanation as the thing it describes.
    const live = css.replace(/\/\*[\s\S]*?\*\//g, '');
    expect(live.toLowerCase()).not.toContain('montserrat');
    expect(files.filter((f) => /montserrat/i.test(f))).toEqual([]);
  });

  it('keeps Auger Mono, which looks unused but is not', () => {
    // .font-auger is used by packages/ui/src/Elements/SearchDropdown.tsx.
    expect(css).toContain('.font-auger');
    expect(files.some((f) => /auger/i.test(f))).toBe(true);
  });
});

describe.each(APPS)('%s font preloads', (app) => {
  const html = readFileSync(resolve(ROOT, `apps/${app}/index.html`), 'utf8');
  const preloaded = [...html.matchAll(/<link rel="preload" href="\/fonts\/([^"]+)"[^>]*>/g)].map((m) => m[1]);

  it('preloads exactly the faces that gate first paint', () => {
    // Three, not eleven: the webapp used to preload 11 faces, which just front-loads ~1 MB.
    expect(preloaded).toHaveLength(3);
  });

  it('preloads files that exist', () => {
    // The webapp's previous preloads pointed at .otf/.ttf paths that no longer exist.
    const missing = preloaded.filter((f) => !existsSync(resolve(fontsDir(app), f)));
    expect(missing, 'a dangling preload wastes a request and warns in console').toEqual([]);
  });

  it('preloads only the latin subset', () => {
    // Preloading .ext would fetch Greek/Cyrillic the page almost certainly does not render.
    expect(preloaded.filter((f) => !f.endsWith('.latin.woff2'))).toEqual([]);
  });

  it('declares the right type and crossorigin', () => {
    // Without crossorigin the font is fetched twice — preload misses, then CSS re-requests.
    for (const f of preloaded) {
      const tag = html.match(new RegExp(`<link rel="preload" href="/fonts/${f.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}"[^>]*>`))![0];
      expect(tag).toContain('type="font/woff2"');
      expect(tag).toContain('crossorigin');
    }
  });

  it('preloads are actually declared in fonts.css', () => {
    const declared = new Set(urlsIn(cssFor(app)));
    expect(preloaded.filter((f) => !declared.has(f))).toEqual([]);
  });
});

describe('payload budget', () => {
  it('keeps the homepage critical faces well under the previous 994 KiB', () => {
    // The eight faces the Lighthouse waterfall showed the homepage downloading.
    const faces = [
      'HelveticaNeueLight', 'HelveticaNeueRoman', 'HelveticaNeueBold',
      'FiraCode-Regular', 'FiraCode-Light', 'FiraCode-Medium', 'FiraCode-SemiBold',
      'benzin-bold',
    ];
    const total = faces.reduce(
      (n, f) => n + statSync(resolve(fontsDir('landing'), `${f}.latin.woff2`)).size, 0,
    ) / 1024;
    expect(total).toBeLessThan(450);
  });

  it('keeps the whole deployed font directory small', () => {
    // Was 12 MB per app.
    const dir = fontsDir('landing');
    const total = readdirSync(dir).reduce((n, f) => n + statSync(resolve(dir, f)).size, 0);
    expect(total / 1024 / 1024).toBeLessThan(4);
  });
});
