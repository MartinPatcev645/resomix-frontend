/**
 * useTrackAnalysis — upload → analyze → result state machine.
 *
 * Everything goes through **Alwyzon** (the single upload front-door), so the upload is
 * login-only and counts against `uploads_per_month`, and every upload also yields a similarity
 * playlist (generated as a background sibling). Alwyzon foregrounds the analysis on the
 * resomix-analysis-service and proxies status/result back:
 *   POST /api/v1/analysis/upload         -> { analysis_id, track_uuid }
 *   GET  /api/v1/analysis/{id}/status    -> { state, part1_ready, progress:{percent}, error }
 *   GET  /api/v1/analysis/{id}/result    -> canonical analysis JSON (partial then full)
 *
 * There is no path straight to the analysis service, for the result or anything else. Its own
 * copy of a result carries internal fields that Alwyzon removes on the way out, so the browser
 * only ever talks to Alwyzon. (A direct-from-cache fetch and a dev-only direct transport both
 * existed once and were removed for that reason.)
 *
 * Part 1 (fast local DSP) renders as soon as the backend checkpoints it; the semantic/GPU part 2
 * fills in when the full result lands (progressive delivery). The snake_case canonical result is
 * adapted to the camelCase `AnalysisData` the dashboard renders via `mapCanonicalToAnalysisData`.
 */

import { useCallback, useEffect, useRef, useState } from "react";
import {
  uploadForAnalysis,
  getAnalysisStatus,
  getAnalysisResult,
} from "@resomix/api-client";
import type { AnalysisData } from "./data.js";
import { mapCanonicalToAnalysisData } from "./mapCanonical.js";
import { makePlayableUrl } from "./audioPlayable.js";
import { shouldDeferToSessionExpiredModal } from "@/utils/sessionExpiryGuard.ts";

// Poll with a gentle backoff: quick at first (part 1 lands in a few seconds), then slower while
// the GPU part 2 runs (often 1-2 min). Halves the request volume vs a fixed 1.5s interval — which
// matters at scale (each concurrent analysis is its own polling client through Alwyzon).
const POLL_INTERVAL_START_MS = 1500;
const POLL_INTERVAL_MAX_MS = 5000;
const POLL_INTERVAL_STEP_MS = 500;
const POLL_TIMEOUT_MS = 10 * 60 * 1000; // give a full-track analysis up to 10 minutes

// The sibling similarity playlist is generated by a background job that runs independently of the
// analysis, so it can appear only AFTER the analysis reports "succeeded" — by which point the main
// poll has stopped. We follow up ONLY while the server explicitly says `sibling_playlist_state:
// "pending"`; a terminal state ends the watch immediately, so we never poll for a playlist that is
// never coming. The timeout is a pure backstop for a worker that dies mid-job and leaves the row
// pending forever — normal completion always ends via the state, not the clock.
const SIBLING_POLL_INTERVAL_MS = 2500;
const SIBLING_POLL_TIMEOUT_MS = 3 * 60 * 1000;

/** `sibling_playlist_state` values that mean "stop waiting" — the playlist will not arrive. */
const SIBLING_TERMINAL_STATES = ["ready", "unavailable", "failed"];

export type AnalysisStatus = "idle" | "uploading" | "analyzing" | "done" | "error";

const delay = (ms: number) => new Promise((r) => setTimeout(r, ms));

/** Normalized status document. */
interface StatusDoc {
  state?: string;
  part1_ready?: boolean;
  percent: number;
  error?: string;
  // Alwyzon enriches status/result with the uploaded track's uuid and its sibling similarity
  // playlist's uuid (owner-gated). The analysis screen plays the upload over HLS by reusing that
  // playlist's seed-only manifest. Absent until the async sibling playlist exists.
  track_uuid?: string;
  playlist_uuid?: string;
  // "pending" | "ready" | "unavailable" | "failed" — whether the sibling playlist is still being
  // generated. An undefined state never starts a watch.
  sibling_playlist_state?: string;
}
type StatusFetcher = (id: string) => Promise<StatusDoc>;
type ResultFetcher = (id: string) => Promise<unknown>;

// --- fetchers -------------------------------------------------------------- //

const alwyzonStatus: StatusFetcher = async (id) => {
  const res = await getAnalysisStatus(id);
  if (!res || (res as { success?: boolean }).success === false) {
    throw new Error((res as { error?: string })?.error || "Status check failed");
  }
  const d = (res as { data: { state?: string; part1_ready?: boolean; progress?: { percent?: number }; error?: string; track_uuid?: string; playlist_uuid?: string; sibling_playlist_state?: string } }).data;
  return {
    state: d.state, part1_ready: d.part1_ready, percent: d.progress?.percent ?? 0, error: d.error,
    track_uuid: d.track_uuid, playlist_uuid: d.playlist_uuid,
    sibling_playlist_state: d.sibling_playlist_state,
  };
};
const alwyzonResult: ResultFetcher = async (id) => {
  const res = await getAnalysisResult(id);
  if (!res || (res as { success?: boolean }).success === false) {
    throw new Error((res as { error?: string })?.error || "Result fetch failed");
  }
  return (res as { data: unknown }).data;
};

/**
 * Poll a job to completion: surface part-1 as soon as it's ready, then the full result. Shared
 * by a fresh upload and by loading an existing id from the URL, over either transport.
 */
async function pollAnalysis(
  id: string,
  isLive: () => boolean,
  onProgress: (pct: number) => void,
  onResult: (data: AnalysisData, done: boolean) => void,
  fetchStatus: StatusFetcher,
  fetchResult: ResultFetcher,
  onMeta: (meta: { trackUuid?: string; playlistUuid?: string; siblingState?: string }) => void = () => {},
): Promise<void> {
  const startedAt = Date.now();
  let part1Shown = false;
  let interval = POLL_INTERVAL_START_MS;
  for (;;) {
    if (!isLive()) return;
    if (Date.now() - startedAt > POLL_TIMEOUT_MS) throw new Error("Analysis timed out");
    const st = await fetchStatus(id);
    // Surface the upload's track uuid + its sibling playlist uuid as soon as they appear (the
    // playlist is created async, so it may land on a later poll). Drives the HLS playback wiring.
    if (st.track_uuid || st.playlist_uuid || st.sibling_playlist_state) {
      onMeta({
        trackUuid: st.track_uuid,
        playlistUuid: st.playlist_uuid,
        siblingState: st.sibling_playlist_state,
      });
    }
    onProgress(Math.min(95, Math.max(10, st.percent)));

    // Stream the interim part-1 result early — BUT skip it when the job is already complete on this
    // very poll (e.g. opening an existing/finished analysis via ?id= or the library). In that case
    // the single final fetch below returns the whole thing, so fetching here too would download the
    // heavy result JSON twice. Fresh uploads still get part-1 early because `part1_ready` lands while
    // the job is still running (state !== "succeeded").
    if (st.part1_ready && !part1Shown && st.state !== "succeeded") {
      part1Shown = true;
      try {
        const raw = await fetchResult(id); // part-1 (partial)
        if (!isLive()) return;
        onResult(mapCanonicalToAnalysisData(raw), false);
      } catch {
        /* part-1 not fetchable yet — keep polling */
      }
    }
    if (st.state === "succeeded") break;
    if (st.state === "failed") throw new Error(st.error || "Analysis failed on the server");
    await delay(interval);
    interval = Math.min(interval + POLL_INTERVAL_STEP_MS, POLL_INTERVAL_MAX_MS);
  }

  const raw = await fetchResult(id); // full result
  if (!isLive()) return;
  onResult(mapCanonicalToAnalysisData(raw), true);
}

/**
 * Watch for the sibling similarity playlist after the analysis job itself has finished.
 *
 * `pollAnalysis` stops the moment the job reports "succeeded", but the playlist is paired
 * asynchronously, so on a fast analysis it may not exist yet at that instant. Without this the CTA
 * stayed disabled for a playlist that showed up seconds later. Resolves as soon as the id appears,
 * or gives up quietly at the timeout (a legacy upload simply has no sibling).
 */
async function pollSiblingPlaylist(
  id: string,
  isLive: () => boolean,
  fetchStatus: StatusFetcher,
  onFound: (playlistUuid: string) => void,
): Promise<void> {
  const startedAt = Date.now();
  while (isLive() && Date.now() - startedAt < SIBLING_POLL_TIMEOUT_MS) {
    await delay(SIBLING_POLL_INTERVAL_MS);
    if (!isLive()) return;
    try {
      const st = await fetchStatus(id);
      if (!isLive()) return;
      if (st.playlist_uuid) {
        onFound(st.playlist_uuid);
        return;
      }
      // The server has decided: the playlist failed, or the job produced none. Stop immediately
      // rather than polling out the backstop timeout for something that will never arrive.
      if (st.sibling_playlist_state && SIBLING_TERMINAL_STATES.includes(st.sibling_playlist_state)) {
        return;
      }
    } catch {
      /* transient status failure — keep watching until the backstop timeout */
    }
  }
}

export function useTrackAnalysis() {
  const [status, setStatus] = useState<AnalysisStatus>("idle");
  const [data, setData] = useState<AnalysisData | null>(null);
  const [fileName, setFileName] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [progress, setProgress] = useState(0);
  const [part1Ready, setPart1Ready] = useState(false);
  const [analysisId, setAnalysisId] = useState<string | null>(null);
  const [audioUrl, setAudioUrl] = useState<string | null>(null);
  const [trackUuid, setTrackUuid] = useState<string | null>(null);
  const [playlistUuid, setPlaylistUuid] = useState<string | null>(null);
  // True only while we are still waiting for the sibling playlist to be paired — drives the CTA's
  // "working on it" affordance, so a disabled button reads as pending rather than permanently dead.
  const [playlistPending, setPlaylistPending] = useState(false);

  const runId = useRef(0);
  const audioUrlRef = useRef<string | null>(null);
  // Mirror `playlistUuid` and the server's sibling state for the async run bodies, whose closures
  // capture stale state values.
  const playlistUuidRef = useRef<string | null>(null);
  const siblingStateRef = useRef<string | undefined>(undefined);

  const rememberPlaylistUuid = useCallback((uuid: string | null) => {
    playlistUuidRef.current = uuid;
    setPlaylistUuid(uuid);
  }, []);

  // Invalidate the current run on unmount. Every async body checks `runId` before touching state,
  // so this both prevents a set-state-after-unmount and, more importantly, stops the sibling watch:
  // it is fire-and-forget and would otherwise keep polling for its full backstop window after the
  // user has navigated away from the analysis screen.
  useEffect(() => () => { runId.current += 1; }, []);

  const setTrackUrl = useCallback((url: string | null) => {
    if (audioUrlRef.current) URL.revokeObjectURL(audioUrlRef.current);
    audioUrlRef.current = url;
    setAudioUrl(url);
  }, []);

  const reset = useCallback(() => {
    runId.current += 1;
    setTrackUrl(null);
    setStatus("idle");
    setData(null);
    setError(null);
    setProgress(0);
    setPart1Ready(false);
    setFileName(null);
    setAnalysisId(null);
    setTrackUuid(null);
    rememberPlaylistUuid(null);
    siblingStateRef.current = undefined;
    setPlaylistPending(false);
  }, [setTrackUrl, rememberPlaylistUuid]);

  const analyze = useCallback(async (file: File) => {
    const myRun = ++runId.current;
    const live = (fn: () => void) => {
      if (runId.current === myRun) fn();
    };

    setFileName(file.name);
    void makePlayableUrl(file).then((url) => live(() => setTrackUrl(url)));
    setError(null);
    setData(null);
    setProgress(0);
    setPart1Ready(false);
    setTrackUuid(null);
    rememberPlaylistUuid(null);
    siblingStateRef.current = undefined;
    setPlaylistPending(false);

    try {
      // 1) upload -> enqueue (real byte-level upload progress)
      live(() => setStatus("uploading"));
      live(() => setProgress(0));

      const up = await uploadForAnalysis(file, (pct) => live(() => setProgress(pct)));
      if (!up || (up as { success?: boolean }).success === false) {
        const reason = (up as { reason?: string })?.reason;
        const serverMsg = (up as { error?: string })?.error;
        const msg =
          reason === "login_required"
            ? "Please log in to analyze a track."
            : reason === "upgrade_required"
              ? serverMsg || "You've used all your uploads this month. Upgrade to analyze more."
              : serverMsg || "Upload failed";
        throw new Error(msg);
      }
      const id = (up as { data: { analysis_id?: string } }).data.analysis_id;
      if (!id) throw new Error("Server did not return an analysis id");
      live(() => setAnalysisId(id)); // -> the page mirrors this into ?id=

      // 2) poll to completion; render part 1 (local DSP) as soon as it's ready.
      live(() => setStatus("analyzing"));
      await pollAnalysis(
        id,
        () => runId.current === myRun,
        (pct) => live(() => setProgress(pct)),
        (d, done) =>
          live(() => {
            setData(d);
            if (done) {
              setProgress(100);
              setStatus("done");
            } else {
              setPart1Ready(true);
            }
          }),
        alwyzonStatus,
        alwyzonResult,
        (meta) => live(() => {
          if (meta.trackUuid) setTrackUuid(meta.trackUuid);
          if (meta.playlistUuid) rememberPlaylistUuid(meta.playlistUuid);
          siblingStateRef.current = meta.siblingState ?? siblingStateRef.current;
        }),
      );

      // The job is done, but the sibling similarity playlist is paired asynchronously and may not
      // exist yet — the main poll stopped the instant the job succeeded. Keep watching (bounded) so
      // the "Find similar tracks" CTA enables itself instead of staying dead for a playlist that
      // lands a moment later.
      // Watch ONLY while the server says the sibling is still being generated. Without a pending
      // state there is nothing to wait for — an older upload that predates automatic pairing, or a
      // job that produced no playlist.
      if (!playlistUuidRef.current && siblingStateRef.current === "pending") {
        live(() => setPlaylistPending(true));
        // Deliberately NOT awaited: this call must still resolve as soon as the ANALYSIS is done.
        // WorkspaceAnalysisPanel clears its submit spinner in `.finally()`, and the watch can run
        // for another minute — awaiting it would hang that spinner. The uuid and the pending flag
        // land through state whenever the watch settles.
        void pollSiblingPlaylist(
          id,
          () => runId.current === myRun,
          alwyzonStatus,
          (uuid) => live(() => rememberPlaylistUuid(uuid)),
        ).finally(() => live(() => setPlaylistPending(false)));
      }
    } catch (e) {
      if (shouldDeferToSessionExpiredModal()) return;
      live(() => setError(e instanceof Error ? e.message : "Analysis failed"));
      live(() => setStatus("error"));
    }
  }, [setTrackUrl, rememberPlaylistUuid]);

  // Open an existing analysis by id (refresh / shared ?id= link).
  const loadById = useCallback(async (id: string) => {
    const myRun = ++runId.current;
    const live = (fn: () => void) => {
      if (runId.current === myRun) fn();
    };

    live(() => {
      setTrackUrl(null);
      setError(null);
      setData(null);
      setProgress(10);
      setPart1Ready(false);
      setAnalysisId(id);
      setStatus("analyzing");
      setTrackUuid(null);
      rememberPlaylistUuid(null);
      siblingStateRef.current = undefined;
      setPlaylistPending(false);
    });

    try {
      await pollAnalysis(
        id,
        () => runId.current === myRun,
        (pct) => live(() => setProgress(pct)),
        (d, done) =>
          live(() => {
            setData(d);
            setFileName(d.identity.filename ?? null);
            if (done) {
              setProgress(100);
              setStatus("done");
            } else {
              setPart1Ready(true);
            }
          }),
        alwyzonStatus,
        alwyzonResult,
        (meta) => live(() => {
          if (meta.trackUuid) setTrackUuid(meta.trackUuid);
          if (meta.playlistUuid) rememberPlaylistUuid(meta.playlistUuid);
          siblingStateRef.current = meta.siblingState ?? siblingStateRef.current;
        }),
      );

      // The job is done, but the sibling similarity playlist is paired asynchronously and may not
      // exist yet — the main poll stopped the instant the job succeeded. Keep watching (bounded) so
      // the "Find similar tracks" CTA enables itself instead of staying dead for a playlist that
      // lands a moment later.
      // Watch ONLY while the server says the sibling is still being generated. Without a pending
      // state there is nothing to wait for — an older upload that predates automatic pairing, or a
      // job that produced no playlist.
      if (!playlistUuidRef.current && siblingStateRef.current === "pending") {
        live(() => setPlaylistPending(true));
        // Deliberately NOT awaited: this call must still resolve as soon as the ANALYSIS is done.
        // WorkspaceAnalysisPanel clears its submit spinner in `.finally()`, and the watch can run
        // for another minute — awaiting it would hang that spinner. The uuid and the pending flag
        // land through state whenever the watch settles.
        void pollSiblingPlaylist(
          id,
          () => runId.current === myRun,
          alwyzonStatus,
          (uuid) => live(() => rememberPlaylistUuid(uuid)),
        ).finally(() => live(() => setPlaylistPending(false)));
      }
    } catch (e) {
      if (shouldDeferToSessionExpiredModal()) return;
      live(() => setError(e instanceof Error ? e.message : "Could not load analysis"));
      live(() => setStatus("error"));
    }
  }, [setTrackUrl, rememberPlaylistUuid]);

  return { status, data, error, progress, fileName, audioUrl, part1Ready, analysisId, trackUuid, playlistUuid, playlistPending, analyze, loadById, reset };
}
