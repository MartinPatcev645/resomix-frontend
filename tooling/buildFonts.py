#!/usr/bin/env python3
"""
Regenerate the subset web fonts and `src/styles/fonts.css` for both apps.

Run from the repo root:  python3 tooling/buildFonts.py

WHY THIS EXISTS
---------------
The original `.otf`/`.ttf` files shipped straight out of `public/fonts` — 12 MB per app, 47 files,
no `woff2`. Each Helvetica Neue face carried 2,200 codepoints (Latin, Greek, Cyrillic, Georgian,
Cherokee, combining marks); the eight faces the landing homepage uses came to 994 KiB on the wire.

Lighthouse put a font at the END of the critical path on both mobile and desktop
(FiraCode-Medium: 1,766 ms mobile / 4,403 ms desktop) and attributed 100 % of the desktop CLS
(0.087) to font swap. So fonts were the single biggest performance problem on the site.

WHAT THIS PRODUCES
------------------
Two subset `woff2` files per face, each with a `unicode-range`, so a page downloads only the
coverage it uses:

  <face>.latin.woff2  Latin + punctuation, super/subscripts, currency, letterlike, number forms,
                      arrows, maths, misc-technical, box-drawing, geometric shapes, misc symbols,
                      dingbats
  <face>.ext.woff2    Greek + Cyrillic — only fetched when such text is actually present

Greek and Cyrillic are kept deliberately: the team is in Thessaloniki and the catalogue carries
international artist names. Georgian and Cherokee are dropped — nothing renders them.

Montserrat (18 faces, 4.6 MB) is excluded entirely: nothing outside `fonts.css` referenced it.
Auger Mono IS kept despite looking unused — `.font-auger` is used by
`packages/ui/src/Elements/SearchDropdown.tsx`.

SOURCES vs OUTPUT
-----------------
Sources live in `fonts-src/` at the repo root and are NOT deployed. Only the generated `.woff2`
files go into each app's `public/fonts/`.

Requires: fontTools + brotli (`pip install fonttools brotli`).
"""
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC_FONTS = ROOT / "fonts-src"
APPS = ("landing", "webapp")

# Everything an English/Western page needs, plus every symbol block the source actually uses
# (verified by scanning the locale file and all TSX for non-ASCII characters: ⌘ ─ ═ ⚠ ♭ ☑ € ↗ …).
LATIN = (
    "U+0000-00FF,"  # Basic Latin + Latin-1 Supplement (incl. soft hyphen U+00AD)
    "U+0100-017F,"  # Latin Extended-A
    "U+0180-024F,"  # Latin Extended-B
    "U+02B0-02FF,"  # Spacing Modifier Letters
    "U+0300-036F,"  # Combining Diacritical Marks
    "U+2000-206F,"  # General Punctuation (— … ’ “ ” • ‑)
    "U+2070-209F,"  # Super/subscripts
    "U+20A0-20BF,"  # Currency (€)
    "U+2100-214F,"  # Letterlike (™ ℠ №)
    "U+2150-218F,"  # Number Forms
    "U+2190-21FF,"  # Arrows (← → ↗ ↔)
    "U+2200-22FF,"  # Mathematical Operators (− ∞ ≈ ≤)
    "U+2300-23FF,"  # Miscellaneous Technical (⌘)
    "U+2500-257F,"  # Box Drawing (─ ═)
    "U+25A0-25FF,"  # Geometric Shapes (▲ ▸ ○ ▢)
    "U+2600-26FF,"  # Miscellaneous Symbols (⚠ ♭ ☑)
    "U+2700-27BF"   # Dingbats
)
EXT = "U+0370-03FF,U+0400-04FF"  # Greek, Cyrillic

# Faces to build: (family, source filename, weight, style). Mirrors the original hand-written
# fonts.css, minus Montserrat.
FACE_RE = re.compile(
    r"@font-face\s*\{\s*font-family:\s*'([^']+)';\s*src:\s*url\('/fonts/([^']+)'\)[^;]*;\s*"
    r"font-weight:\s*(\d+);\s*font-style:\s*(\w+);\s*font-display:\s*(\w+);\s*\}",
    re.S,
)

HEADER = """/* ─────────────────────────────────────────────────────────────────────────────
   Font declarations — GENERATED by tooling/buildFonts.py. Do not hand-edit.

   Every face ships as two subset .woff2 files with a `unicode-range`, so a page
   downloads only the coverage it actually uses:

     *.latin.woff2  Latin + punctuation, currency, arrows, maths, box-drawing,
                    geometric shapes, misc symbols and dingbats
     *.ext.woff2    Greek + Cyrillic — fetched only when such text is present

   Why: the original .otf/.ttf files carried 1,200-2,200 codepoints each
   (including Georgian and Cherokee) and the eight faces the homepage uses came
   to 994 KiB on the wire. Lighthouse put a font at the END of the critical path
   on both mobile and desktop, and attributed 100% of the desktop CLS (0.087) to
   font swap. Subset + woff2 cuts that to roughly a third for an English page.

   Montserrat was removed entirely — 18 faces, 4.6 MB, referenced by nothing.
   Auger Mono is kept: .font-auger is used by ui/Elements/SearchDropdown.tsx.
   ───────────────────────────────────────────────────────────────────────────── */

"""


def face_block(family, base, weight, style, display, tag, unicode_range):
    return (
        f"@font-face {{\n"
        f"    font-family: '{family}';\n"
        f"    src: url('/fonts/{base}.{tag}.woff2') format('woff2');\n"
        f"    font-weight: {weight};\n"
        f"    font-style: {style};\n"
        f"    font-display: {display};\n"
        f"    unicode-range: {unicode_range};\n"
        f"}}\n\n"
    )


def main():
    if not SRC_FONTS.is_dir():
        sys.exit(f"missing {SRC_FONTS} — the original .otf/.ttf sources live there")

    current = (ROOT / "apps/landing/src/styles/fonts.css").read_text(encoding="utf-8")
    faces = [f for f in FACE_RE.findall(current) if not f[1].lower().startswith("montserrat")]
    if not faces:
        sys.exit("no @font-face blocks parsed — has fonts.css already been regenerated?")

    out_dirs = [ROOT / f"apps/{a}/public/fonts" for a in APPS]
    for d in out_dirs:
        d.mkdir(parents=True, exist_ok=True)

    built = []
    for family, filename, weight, style, display in faces:
        # After the first run, fonts.css references the generated names; map back to the source.
        base = re.sub(r"\.(latin|ext)\.woff2$", "", filename)
        base = Path(base).stem
        source = next((SRC_FONTS / f"{base}{ext}" for ext in (".otf", ".ttf")
                       if (SRC_FONTS / f"{base}{ext}").exists()), None)
        if source is None:
            sys.exit(f"no source font for {base} in {SRC_FONTS}")

        for tag, rng in (("latin", LATIN), ("ext", EXT)):
            target = out_dirs[0] / f"{base}.{tag}.woff2"
            subprocess.run(
                ["pyftsubset", str(source), f"--unicodes={rng}", "--layout-features=*",
                 "--flavor=woff2", f"--output-file={target}"],
                check=True, capture_output=True,
            )
        built.append((family, base, weight, style, display))

    # Utility classes are hand-written; preserve them verbatim from the existing file.
    util = re.search(r"(/\* Force font loading.*?)(?=@font-face|\Z)", current, re.S)
    util = re.sub(r"\.font-montserrat[^}]*\}\s*", "", util.group(1)) if util else ""

    css = [HEADER]
    for family, base, weight, style, display in built:
        css.append(face_block(family, base, weight, style, display, "latin", LATIN))
        css.append(face_block(family, base, weight, style, display, "ext", EXT))
    css.append(util.rstrip() + "\n")
    css = "".join(css)

    for app, d in zip(APPS, out_dirs):
        if d != out_dirs[0]:
            for f in d.glob("*.woff2"):
                f.unlink()
            for f in out_dirs[0].glob("*.woff2"):
                (d / f.name).write_bytes(f.read_bytes())
        (ROOT / f"apps/{app}/src/styles/fonts.css").write_text(css, encoding="utf-8")

    total = sum(f.stat().st_size for f in out_dirs[0].glob("*.woff2"))
    print(f"built {len(built)} faces -> {len(built) * 2} files, {total / 1024 / 1024:.2f} MB")
    print(f"wrote fonts.css to: {', '.join(APPS)}")


if __name__ == "__main__":
    main()
